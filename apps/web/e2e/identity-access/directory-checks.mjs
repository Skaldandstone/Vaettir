/* global document, innerWidth */
import assert from "node:assert/strict";
import path from "node:path";

export async function checkDirectory(page, output) {
  const section = () => page.getByRole("region", { name: "Directory access" });
  const dialog = () => page.getByRole("dialog", { name: "External group mappings" });
  for (const theme of ["dark", "light"]) {
    await page.evaluate(() => { localStorage.removeItem("directory-fixture"); localStorage.removeItem("fail-directory"); });
    await page.reload();
    await page.evaluate(theme => document.documentElement.dataset.theme = theme, theme);
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.getByRole("button", { name: "Sign-in & directory", exact: true }).click();
    const sso = page.getByRole("region", { name: "Single sign-on" });
    await page.evaluate(() => { localStorage.setItem("sso-fixture", "unavailable"); localStorage.setItem("sso-open-count", "0"); });
    await sso.getByRole("button", { name: "Check setup" }).click();
    await sso.getByRole("status").filter({ hasText: "not been enabled" }).waitFor();
    assert.equal(await sso.getByRole("button", { name: "Open provider setup" }).count(), 0);
    await page.evaluate(() => localStorage.setItem("sso-fixture", "provider-admin-required"));
    await sso.getByRole("button", { name: "Refresh status" }).click();
    await sso.getByRole("status").filter({ hasText: "administrator" }).waitFor();
    await page.evaluate(() => localStorage.setItem("sso-fixture", "ready"));
    await sso.getByRole("button", { name: "Refresh status" }).click();
    await sso.getByRole("button", { name: "Open provider setup" }).waitFor();
    assert.equal(await page.evaluate(() => localStorage.getItem("sso-open-count")), "0");
    await page.screenshot({ path: path.join(output, `setup-${theme}.png`), fullPage: true });
    await page.evaluate(() => localStorage.setItem("sso-fixture", "error"));
    await sso.getByRole("button", { name: "Open provider setup" }).click();
    await sso.getByRole("alert").filter({ hasText: "Could not verify" }).waitFor();
    assert.equal(await page.evaluate(() => localStorage.getItem("sso-open-count")), "0");
    await page.evaluate(() => localStorage.setItem("sso-fixture", "ready"));
    await sso.getByRole("button", { name: "Check setup" }).click();
    await sso.getByRole("button", { name: "Open provider setup" }).click();
    assert.equal(await page.evaluate(() => localStorage.getItem("sso-open-count")), "1");
    await section().getByRole("button", { name: "Edit mappings" }).click();
    assert.equal(await dialog().getByRole("button", { name: "Save mappings" }).isDisabled(), true);
    await dialog().getByRole("button", { name: "Add mapping" }).click();
    await dialog().getByRole("alert").filter({ hasText: "Choose a group" }).waitFor();
    await dialog().getByLabel("External group", { exact: true }).selectOption({ index: 1 });
    await dialog().getByLabel("Published role", { exact: true }).selectOption("reviewer");
    await dialog().getByRole("checkbox", { name: /Synthetic UI verification/ }).check();
    await dialog().getByRole("button", { name: "Add mapping" }).click();
    await page.screenshot({ path: path.join(output, `mapping-${theme}.png`), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await dialog().getByRole("button", { name: "Save mappings" }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, `mapping-narrow-${theme}.png`), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.keyboard.press("Tab");
    assert.equal(await page.evaluate(() => !!document.activeElement.closest('[role="dialog"],dialog')), true);
    await dialog().getByRole("button", { name: "Save mappings" }).click();
    await section().getByRole("status").filter({ hasText: "Mappings saved" }).waitFor();
    await page.reload();
    await page.evaluate(theme => document.documentElement.dataset.theme = theme, theme);
    await page.getByRole("button", { name: "Sign-in & directory", exact: true }).click();
    await section().getByRole("button", { name: "Edit mappings" }).click();
    assert.equal(await dialog().getByRole("button", { name: "Remove mapping 1" }).count(), 1);
    assert.equal(await dialog().getByRole("button", { name: "Save mappings" }).isDisabled(), true);
    // Removing and recreating the same rule is not a permission change.
    await dialog().getByRole("button", { name: "Remove mapping 1" }).click();
    assert.equal(await dialog().getByRole("button", { name: "Save mappings" }).isEnabled(), true);
    await dialog().getByLabel("External group", { exact: true }).selectOption({ index: 1 });
    await dialog().getByLabel("Published role", { exact: true }).selectOption("reviewer");
    await dialog().getByRole("checkbox", { name: /Synthetic UI verification/ }).check();
    await dialog().getByRole("button", { name: "Add mapping" }).click();
    assert.equal(await dialog().getByRole("button", { name: "Save mappings" }).isDisabled(), true);
    await dialog().getByText("No mapping changes.", { exact: true }).waitFor();
    await dialog().getByRole("button", { name: "Remove mapping 1" }).click();
    await page.evaluate(() => localStorage.setItem("fail-directory", "after"));
    await dialog().getByRole("button", { name: "Save mappings" }).click();
    await dialog().getByRole("alert").filter({ hasText: "could not be confirmed" }).waitFor();
    assert.equal(await dialog().getByRole("button", { name: "Save mappings" }).count(), 0);
    await dialog().getByRole("button", { name: "Reload status" }).click();
    await section().getByRole("button", { name: "Edit mappings" }).click();
    assert.equal(await dialog().getByRole("button", { name: "Remove mapping 1" }).count(), 0);
    await page.keyboard.press("Escape");
    await page.evaluate(() => localStorage.removeItem("fail-directory"));
    await section().getByRole("button", { name: "Disable access" }).click();
    await page.getByRole("dialog", { name: "Disable directory access?" }).getByRole("button", { name: "Cancel" }).click();
    assert.equal(await section().getByRole("button", { name: "Disable access" }).isEnabled(), true);
    await section().getByRole("button", { name: "Disable access" }).click();
    await page.getByRole("dialog", { name: "Disable directory access?" }).getByRole("button", { name: "Disable access", exact: true }).click();
    await section().getByRole("status").filter({ hasText: "Directory access disabled" }).waitFor();
    assert.equal(await section().getByRole("button", { name: "Disable access" }).isDisabled(), true);
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.screenshot({ path: path.join(output, `directory-${theme}.png`), fullPage: true });
    await page.evaluate(() => {
      const connections = JSON.parse(localStorage.getItem("directory-fixture"));
      Object.assign(connections[0], { enabled: true, lastObservedAt: null, observedMembers: 0, activeMembers: 0, staleMembers: 0 });
      localStorage.setItem("directory-fixture", JSON.stringify(connections));
    });
    await section().getByRole("button", { name: "Reload", exact: true }).click();
    await section().getByText("Not yet synced", { exact: true }).first().waitFor();
    assert.equal(await section().getByText("Observations current", { exact: true }).count(), 0);
    await page.screenshot({ path: path.join(output, `unobserved-${theme}.png`), fullPage: true });
    await page.evaluate(() => {
      const connections = JSON.parse(localStorage.getItem("directory-fixture"));
      connections[0].lastObservedAt = "2026-10-22T12:00:00.000Z";
      localStorage.setItem("directory-fixture", JSON.stringify(connections));
    });
    await section().getByRole("button", { name: "Reload", exact: true }).click();
    await section().getByText("No members observed", { exact: true }).waitFor();
  }
  await page.evaluate(() => localStorage.setItem("directory-fixture", "[]"));
  await section().getByRole("button", { name: "Reload", exact: true }).click();
  await section().getByRole("heading", { name: "No directory connected" }).waitFor();
}
