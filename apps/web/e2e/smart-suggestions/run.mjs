/* global document, window, innerWidth */
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { createServer } from "node:http";
import { fileURLToPath } from "node:url";
import path from "node:path";
const web = fileURLToPath(new URL("../../", import.meta.url));
const require = createRequire(path.join(web, "package.json"));
const viteRequire = createRequire(createRequire(require.resolve("vitest")).resolve("vite"));
const { build } = viteRequire("esbuild"), { chromium } = require("@playwright/test");
const output = path.resolve(web, "../../.local/smart-suggestions-browser-20261028"); await mkdir(output, { recursive: true });
const boundary = path.join(web, "e2e/smart-suggestions/boundary.jsx");
const bundle = await build({ entryPoints: [path.join(web, "e2e/smart-suggestions/fixture.jsx")], bundle: true, write: false, jsx: "automatic", platform: "browser", nodePaths: [path.join(web, "node_modules")], alias: { "@": web }, plugins: [{ name: "synthetic-transport", setup(builder) { builder.onResolve({ filter: /^(@clerk\/nextjs|.*\/trpcReact)$/ }, () => ({ path: boundary })); } }] });
const css = (await readFile(path.join(web, "app/globals.css"), "utf8")).replace(/^@import[^\r\n]+\r?\n/, "") + "\n" + await readFile(path.join(web, "app/workbench.css"), "utf8");
const server = createServer((req, res) => { res.setHeader("Content-Type", req.url === "/bundle.js" ? "application/javascript" : "text/html"); res.end(req.url === "/bundle.js" ? bundle.outputFiles[0].text : `<!doctype html><html data-theme="dark"><head><meta name="viewport" content="width=device-width,initial-scale=1"><style>${css}</style></head><body><div id="root"></div><script src="/bundle.js"></script></body></html>`); });
await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
const origin = `http://127.0.0.1:${server.address().port}`, browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 960 } });
const errors = [], checks = [];
page.on("pageerror", error => errors.push(error.message));
await page.route("**/*", route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); };
try {
  await page.goto(origin);
  check("analysis requires explicit approval", await page.getByRole("button", { name: "Suggest mappings", exact: true }).isDisabled());
  await page.getByLabel(/I approve sending the column names/).check();
  await page.getByRole("button", { name: "Suggest mappings", exact: true }).click();
  await page.getByRole("button", { name: "Use selected mappings in preview" }).waitFor();
  check("analysis has no mapping side effects", await page.getByTestId("mapping-state").textContent() === "No mapping changes applied");
  await page.getByRole("button", { name: "Use selected mappings in preview" }).click();
  await page.getByText("Mapped title: Scenario text", { exact: true }).waitFor();
  await page.getByLabel(/I approve sending these selected case definitions/).check();
  await page.getByRole("button", { name: "Generate suggestions", exact: true }).click();
  await page.getByRole("button", { name: "Use selected suggestions in import preview" }).waitFor();
  check("import review is separate from persistence", await page.evaluate(() => window.smartFixture.saves.length === 0 && window.smartFixture.writes === 0));
  await page.getByText("Restore purchase · high confidence", { exact: true }).click();
  await page.getByText("Avoid duplicate charge · high confidence", { exact: true }).click();
  for (const theme of ["dark", "light"]) for (const width of [1280, 390]) {
    await page.setViewportSize({ width, height: 960 }); await page.evaluate(theme => document.documentElement.dataset.theme = theme, theme);
    check(`${theme}/${width} wraps content`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: path.join(output, `import-${theme}-${width}.png`), fullPage: true });
  }
  await page.getByRole("button", { name: "Use selected suggestions in import preview" }).click();
  await page.waitForFunction(() => document.querySelector('[data-testid="patches"]').textContent.includes('Billing/Restoration'));
  const patches = JSON.parse(await page.getByTestId("patches").textContent());
  check("reviewed import patches contain only selected metadata", patches.length === 2 && patches.every(p => p.suitePath === "Billing/Restoration" && p.priority === "HIGH" && !Object.hasOwn(p, "when")));
  await page.goto(origin + "/?stored");
  await page.getByLabel(/I approve sending these selected case definitions/).check();
  await page.getByRole("button", { name: "Generate suggestions", exact: true }).click();
  await page.getByRole("button", { name: "Apply selected changes", exact: true }).waitFor();
  await page.getByText("Restore purchase · high confidence", { exact: true }).click();
  await page.screenshot({ path: path.join(output, "existing-review-light-390.png"), fullPage: true });
  await page.getByRole("button", { name: "Apply selected changes", exact: true }).click();
  await page.getByRole("button", { name: "Retry the exact reviewed save" }).waitFor();
  check("unknown write retains and locks the review", await page.getByRole("button", { name: "Discard suggestions", exact: true }).isDisabled());
  await page.evaluate(() => { window.smartFixture.actor = "other-actor"; window.smartFixture.notify(); });
  await page.getByText(/Restore the original signed-in account, workspace/).waitFor();
  check("account change withholds old case review", await page.getByText("Restore purchase · high confidence", { exact: true }).count() === 0);
  await page.evaluate(() => { window.smartFixture.actor = "synthetic-actor"; window.smartFixture.notify(); });
  await page.getByRole("button", { name: "Retry the exact reviewed save" }).click();
  await page.getByText("Reviewed changes saved", { exact: true }).waitFor();
  check("lost response reuses exact request and applies once", await page.evaluate(() => window.smartFixture.writes === 1 && window.smartFixture.saves.length === 2 && JSON.stringify(window.smartFixture.saves[0]) === JSON.stringify(window.smartFixture.saves[1])));
  await page.goto(origin + "/?stored");
  await page.evaluate(() => { window.smartFixture.reject = true; });
  await page.getByLabel(/I approve sending these selected case definitions/).check();
  await page.getByRole("button", { name: "Generate suggestions", exact: true }).click();
  await page.getByRole("button", { name: "Apply selected changes", exact: true }).click();
  await page.getByText(/server refused this save before committing/).waitFor();
  check("definitive refusal permits a fresh review", await page.getByRole("button", { name: "Discard suggestions", exact: true }).isEnabled());
  check("refused save writes nothing", await page.evaluate(() => window.smartFixture.writes === 0));
  check("no runtime errors", errors.length === 0);
  await writeFile(path.join(output, "review.json"), JSON.stringify({ checks, errors, provider: "synthetic transport", actualComponents: true, hostedAcceptance: false }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, output }));
} finally { await browser.close(); server.close(); }
